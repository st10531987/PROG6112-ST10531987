    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
       String customer = txtCustomer.getText().trim();
String product = cmbProduct.getSelectedItem().toString();

if (customer.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Please enter customer name.");
    return;
}

try {
    double price = Double.parseDouble(
        txtPrice.getText().trim()
    );

    if (!Double.isFinite(price) || price < 0) {
        throw new NumberFormatException();
    }

    // Calculate VAT, commission and total
   ProductCalculations calculations =
        new ProductCalculations(price);

double vat = calculations.GetVat();
double commission = calculations.GetCommission();
double total = calculations.GetTotal();

    // Prepare report
    String report = String.format(
        "Customer Name: %s%n"
        + "Product: %s%n"
        + "VAT: R %.2f%n"
        + "COMMISSION: R %.2f%n"
        + "TOTAL: R %.2f",
        customer, product, vat, commission, total
    );

    // Save the information to data.txt
    try (java.io.FileWriter writer =
            new java.io.FileWriter("data.txt", true)) {

        writer.write("DATA LOG\n");
        writer.write(
            "********************************\n"
        );
        writer.write(report);
        writer.write("\n");
        writer.write(
            "********************************\n\n"
        );

    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Error saving file: " + e.getMessage()
        );
        return;
    }

    // Display report in a message box
    javax.swing.JOptionPane.showMessageDialog(
        this,
        report,
        "Message",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Please enter a valid product price."
    );
} 
                                                                                                           
    }//GEN-LAST:event_btnProcessActionPerformed

